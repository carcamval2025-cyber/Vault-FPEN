# 4. Un vector y una operación vectorizada
L = Lamina("s1-vector", 760, 300, "Arriba, las cuatro cajas 4200, 4550, 4100 y 4800 forman un solo objeto llamado ingresos. Abajo, la misma operación por 1.05 se aplica a las cuatro posiciones a la vez y da 4410, 4777.5, 4305 y 5040.")
L.text(20, 28, "Un vector: cuatro valores, un solo objeto", "t")
L.rect(150, 44, 580, 74, C["blues"], C["blue"], 12, 1.4, ' stroke-dasharray="6 4"')
L.text(30, 88, "ingresos", "m b", "start", C["blue"], 15)
L.flecha("M112 83 H 146", "pb", C["blue"], 1.8)
xs = [168, 308, 448, 588]
for x, v, m in zip(xs, ["4200", "4550", "4100", "4800"], ["ene", "feb", "mar", "abr"]):
    L.caja(x, 56, 124, 50, v, m)
for x in xs:
    L.flecha("M%g 120 V 182" % (x + 62), "pa", C["amber"], 2)
L.rect(262, 136, 234, 30, "#ffffff", C["amberk"], 15, 1.4)
L.text(379, 156, "× 1.05 en las 4 a la vez", "b", "middle", C["amber"], 13)
for x, v in zip(xs, ["4410", "4777.5", "4305", "5040"]):
    L.caja(x, 190, 124, 50, v, None, C["ambers"], C["amberk"])
L.text(30, 222, "ingresos * 1.05", "m b", "start", C["amber"], 13)
L.text(379, 276, "El resultado tiene el mismo largo: 4 valores, no un total.", "s", "middle")
L.guardar()
